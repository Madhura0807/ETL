"""Write sql/schema_mysql.sql from the SQLAlchemy metadata models (single source of truth)."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from sqlalchemy.dialects import mysql
from sqlalchemy.schema import CreateIndex, CreateTable

from src.db.models import metadata

lines = ["-- Pipeline METADATA tables for MySQL. Generated by scripts/export_ddl.py - do not edit by hand.",
         "-- The framework also creates these automatically (CREATE TABLE IF NOT EXISTS semantics).",
         "-- Business tables are created from the data on first load.", ""]
for table in metadata.sorted_tables:
    lines.append(str(CreateTable(table, if_not_exists=True).compile(dialect=mysql.dialect())).strip() + ";")
    for idx in sorted(table.indexes, key=lambda i: i.name):
        lines.append(str(CreateIndex(idx).compile(dialect=mysql.dialect())).strip() + ";")
    lines.append("")
out = Path(__file__).resolve().parents[1] / "sql" / "schema_mysql.sql"
out.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {out}")
